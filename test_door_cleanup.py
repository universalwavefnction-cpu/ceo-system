"""Merge cleanup removes a clean order worktree, and keeps one that holds work saved since the review."""
import shutil

from test_door import DoorCase

SLUG = "941-after-review"
LATER = "The only saved copy of a change made after the reviewed commit.\n"


class MergeCleanup(DoorCase):
    def worktree(self):
        """A reviewed order, its worktree clean, as the owner finds it before the door merges."""
        self.reviewed(SLUG)
        wt = self.repo / self.read(SLUG)["worktree"]
        self.assertEqual(self.git("-C", str(wt), "status", "--porcelain", "--untracked-files=all"), "")
        return wt

    def listed(self, wt):
        return str(wt) in self.git("worktree", "list", "--porcelain")

    def branch(self):
        return self.git("for-each-ref", "--format=%(objectname)", f"refs/heads/order/{SLUG}")

    def kept(self, wt, door):
        """The door merged the pull request, took the cleanup again later, and touched nothing here."""
        self.assertEqual(door.returncode, 2, door.stdout + door.stderr)
        self.assertIn("worktree", door.stdout)
        self.assertTrue(self.read(SLUG).get("merged"))
        self.assertNotIn("cleared", self.read(SLUG))
        self.assertTrue(self.listed(wt))
        self.assertTrue(self.branch())

    def settled(self, wt, door):
        self.assertEqual(door.returncode, 0, door.stdout + door.stderr)
        self.assertIn("cleared", self.read(SLUG))
        self.assertFalse(wt.exists())
        self.assertFalse(self.listed(wt))

    def test_clean_worktree_is_removed_and_its_branch_with_it(self):
        wt = self.worktree()
        self.settled(wt, self.door())
        self.assertEqual(self.branch(), "")

    def test_tracked_edit_stays_until_the_owner_discards_it(self):
        wt = self.worktree()
        (wt / f"{SLUG}.txt").write_text(LATER)
        self.kept(wt, self.door())
        self.assertEqual((wt / f"{SLUG}.txt").read_text(), LATER)
        self.assertEqual(self.door().returncode, 0)  # the owner has not decided: the door waits, and changes nothing
        self.assertEqual((wt / f"{SLUG}.txt").read_text(), LATER)
        self.git("-C", str(wt), "checkout", "--", f"{SLUG}.txt")
        self.settled(wt, self.door())
        self.assertEqual(self.branch(), "")

    def test_staged_change_stays(self):
        wt = self.worktree()
        (wt / "staged.txt").write_text(LATER)
        self.git("-C", str(wt), "add", "staged.txt")
        self.kept(wt, self.door())
        self.assertEqual((wt / "staged.txt").read_text(), LATER)
        self.assertEqual(self.git("-C", str(wt), "diff", "--cached", "--name-only"), "staged.txt")

    def test_untracked_file_stays(self):
        wt = self.worktree()
        (wt / "next-change.txt").write_text(LATER)
        self.kept(wt, self.door())
        self.assertEqual((wt / "next-change.txt").read_text(), LATER)

    def test_untracked_file_stays_when_git_is_set_not_to_show_it(self):
        wt = self.worktree()
        self.git("config", "status.showUntrackedFiles", "no")
        (wt / "next-change.txt").write_text(LATER)
        self.assertEqual(self.git("-C", str(wt), "status", "--porcelain"), "")  # the setting hides it from a plain status
        self.kept(wt, self.door())
        self.assertEqual((wt / "next-change.txt").read_text(), LATER)

    def test_untracked_file_in_a_new_folder_stays(self):
        wt = self.worktree()
        (wt / "notes" / "deep").mkdir(parents=True)
        (wt / "notes" / "deep" / "next.txt").write_text(LATER)
        self.kept(wt, self.door())
        self.assertEqual((wt / "notes" / "deep" / "next.txt").read_text(), LATER)

    def test_commit_made_after_review_keeps_its_branch(self):
        wt = self.worktree()
        (wt / "next-change.txt").write_text(LATER)
        self.git("-C", str(wt), "add", "next-change.txt")
        self.git("-C", str(wt), "commit", "-qm", "Change after review")
        later = self.git("-C", str(wt), "rev-parse", "HEAD")
        self.assertNotEqual(later, self.read(SLUG)["head"])
        door = self.door()  # nothing is uncommitted: the worktree goes, and the branch, which holds the commit, stays
        self.assertEqual(door.returncode, 0, door.stdout + door.stderr)
        self.assertIn("cleared", self.read(SLUG))
        self.assertFalse(wt.exists())
        self.assertEqual(self.branch(), later)

    def test_ignored_output_does_not_keep_a_worktree(self):
        wt = self.worktree()
        with (self.repo / ".git" / "info" / "exclude").open("a") as exclude:
            exclude.write("build/\n")  # what the project ignores is not work: tests and builds leave it
        (wt / "build").mkdir()
        (wt / "build" / "output.txt").write_text("regenerated by the next build\n")
        self.assertEqual(self.git("-C", str(wt), "status", "--porcelain", "--untracked-files=all"), "")
        self.settled(wt, self.door())

    def test_worktree_git_refuses_to_remove_is_not_deleted_by_hand(self):
        wt = self.worktree()
        self.git("worktree", "lock", str(wt))
        self.kept(wt, self.door())
        self.assertTrue((wt / ".git").is_file())
        self.assertEqual((wt / f"{SLUG}.txt").read_text(), f"{SLUG}.txt\n")
        self.git("worktree", "unlock", str(wt))
        self.assertEqual(self.door().returncode, 0)
        self.assertIn("cleared", self.read(SLUG))
        self.assertFalse(wt.exists())

    def test_directory_that_is_not_a_worktree_is_not_deleted_by_hand(self):
        wt = self.worktree()
        (wt / ".git").unlink()  # what a removal cut off halfway leaves: the files, and no link to the repository
        (wt / "next-change.txt").write_text(LATER)
        door = self.door()
        self.assertEqual(door.returncode, 2, door.stdout + door.stderr)
        self.assertNotIn("cleared", self.read(SLUG))
        self.assertEqual((wt / "next-change.txt").read_text(), LATER)

    def test_worktree_already_gone_is_settled(self):
        wt = self.worktree()
        shutil.rmtree(wt)  # a door cut off after git took the folder: git still lists it until pruned
        self.assertTrue(self.listed(wt))
        self.settled(wt, self.door())
        self.assertEqual(self.branch(), "")
